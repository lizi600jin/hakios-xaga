#!/usr/bin/env python3
"""Turn mali_csffw.bin into a C header the kernel can carry.

The GPU driver embeds the firmware because at run time there is nowhere to read it from: the
kernel has no filesystem of its own, and the vendor copies in /vendor/firmware belong to
Android's system partition which this kernel does not mount.

Written as bytes, not as a hex string: Panthor's own generator writes "0x%02x," per byte, and
for a 258 KB image that is a 1.7 MB source file. It compiles, but it is a lot of text for
something no one will ever read.

    python3 mtk/tools/mkmalifw.py /path/to/mali_csffw.bin > mtk/mt6895/drivers/gpu/hakios.mali_fw.h
"""
import sys, hashlib

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else '/tmp/mtk_csffw.bin'
    data = open(src, 'rb').read()
    if len(data) < 20 or int.from_bytes(data[:4], 'little') != 0xc3f13a6e:
        sys.exit('%s does not start with the CSF firmware magic' % src)
    digest = hashlib.sha256(data).hexdigest()
    out = sys.stdout
    out.write('/* Generated by mtk/tools/mkmalifw.py from the vendor image; do not edit.\n')
    out.write(' *\n')
    out.write(' * %d bytes, sha256 %s\n' % (len(data), digest))
    out.write(' *\n')
    out.write(' * The header says version %d.%d and the entry table ends at %d, which is\n'
              % (data[5], data[4], int.from_bytes(data[16:20], 'little')))
    out.write(' * what loadFirmware() checks before it trusts any of it.\n')
    out.write(' */\n\n')
    out.write('#ifndef _HAKIOS_MALI_FW_H_\n#define _HAKIOS_MALI_FW_H_\n\n')
    out.write('#define MALI_FW_LENGTH  %du\n' % len(data))
    out.write('#define MALI_FW_SHA256  "%s"\n\n' % digest)
    out.write('static const unsigned char kMaliFirmware[MALI_FW_LENGTH] = {\n')
    for i in range(0, len(data), 16):
        out.write('\t' + ''.join('0x%02x,' % b for b in data[i:i+16]) + '\n')
    out.write('};\n\n#endif /* _HAKIOS_MALI_FW_H_ */\n')

main()
